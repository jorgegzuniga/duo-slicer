#!/bin/sh
# Builds the engine harness, slices a generated two-colour tile for every supported printer and checks the G-code.
set -e
cd "$(dirname "$0")/.."
./build_cli.sh
T=$(mktemp -d)
python3 tools/make_test_3mf.py "$T/tile.3mf"
echo '{}' > "$T/opts.json"

# Bambu A1: packaged .gcode.3mf with MD5 and slice info
./a1cli Resources/profiles/bambu-a1.json "$T/tile.3mf" 0 "$T/opts.json" "$T/a1.gcode.3mf" | tee "$T/a1.json"
python3 - "$T" <<'PY'
import json, zipfile, subprocess, sys, hashlib
t = sys.argv[1]
s = json.load(open(t + '/a1.json'))
assert s.get('ok'), s
assert s['file_kind'] == 'gcode.3mf', s
assert s['layers'] == 20, s['layers']
assert s['tool_changes'] >= 1, s
z = zipfile.ZipFile(t + '/a1.gcode.3mf')
g = z.read('Metadata/plate_1.gcode')
assert z.read('Metadata/plate_1.gcode.md5').decode() == hashlib.md5(g).hexdigest().upper()
assert 'printer_model_id" value="N2S"' in z.read('Metadata/slice_info.config').decode()
open(t + '/a1.gcode', 'wb').write(g)
out = subprocess.run([sys.executable, 'tools/check_gcode.py', t + '/a1.gcode'], capture_output=True, text=True).stdout
print(out)
assert 'problems 0' in out, out
PY

# Snapmaker U1: plain G-code, one toolhead per colour, Orca-style metadata
echo '{"tool_map":[2,0]}' > "$T/u1opts.json"
./a1cli Resources/profiles/snapmaker-u1.json "$T/tile.3mf" 0 "$T/u1opts.json" "$T/u1.gcode" | tee "$T/u1.json"
python3 - "$T" <<'PY'
import json, subprocess, sys, re
t = sys.argv[1]
s = json.load(open(t + '/u1.json'))
assert s.get('ok'), s
assert s['file_kind'] == 'gcode', s
assert s['tool_map'][:2] == [2, 0], s['tool_map']
g = open(t + '/u1.gcode').read()
assert g.startswith('; HEADER_BLOCK_START\n; generated by OrcaSlicer'), g[:80]
assert '\nT2\n' in g and '\nT0\n' in g, 'tool changes missing'
assert 'EXCLUDE_OBJECT_DEFINE NAME=' in g
assert re.search(r'; estimated printing time \(normal mode\) = ', g)
assert '; CONFIG_BLOCK_START' in g and '; filament_colour = ' in g
out = subprocess.run([sys.executable, 'tools/check_gcode.py', t + '/u1.gcode', '--bed', '0.5,1,270.5,271', '--tools', '4'], capture_output=True, text=True).stdout
print(out)
assert 'problems 0' in out, out
PY

# placement edits: place, arrange, move between plates, new and removed plates, undo, export and reopen
SRC=$(ls Engine/src/*.cpp | grep -v '/net.cpp$')
c++ -O1 -std=c++17 -Wall -Wno-sign-compare -IEngine/third_party -IEngine/src -IEngine/include tools/t_place.cpp $SRC Engine/third_party/clipper2/*.cpp -lz -o "$T/t_place"
"$T/t_place" Resources/profiles/bambu-x1c.json Resources/demo.3mf
"$T/t_place" Resources/profiles/bambu-a1-mini.json Resources/demo.3mf

# every printer bundle
python3 tools/validate_printers.py ./a1cli "$T/tile.3mf"
echo "engine self-test passed"
